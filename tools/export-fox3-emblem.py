"""Extract black ink, thin to a skeleton and spatially sample. Never ships the source PNG."""
import hashlib, math, pathlib
from PIL import Image, ImageDraw
root=pathlib.Path(__file__).resolve().parent.parent
source=root/'tools/素材参考/爆炸特效.png'
image=Image.open(source).convert('RGBA')
white=Image.new('RGBA',image.size,'white'); white.alpha_composite(image)
gray=white.convert('L').resize((256,256),Image.Resampling.LANCZOS)
ink={(x,y) for y in range(1,255) for x in range(1,255) if gray.getpixel((x,y))<110}
pixels=set(ink)
# Zhang-Suen thinning: preserve line topology, including the eye's white highlights.
while True:
    removed=0
    for phase in (0,1):
        delete=[]
        for x,y in pixels:
            p=[(x,y-1),(x+1,y-1),(x+1,y),(x+1,y+1),(x,y+1),(x-1,y+1),(x-1,y),(x-1,y-1)]
            b=[int(q in pixels) for q in p]
            if not 2<=sum(b)<=6 or sum(b[i]==0 and b[(i+1)%8]==1 for i in range(8))!=1: continue
            if phase==0 and b[0]*b[2]*b[4]==0 and b[2]*b[4]*b[6]==0: delete.append((x,y))
            if phase==1 and b[0]*b[2]*b[6]==0 and b[0]*b[4]*b[6]==0: delete.append((x,y))
        pixels.difference_update(delete); removed+=len(delete)
    if not removed: break
points=[]; spacing=4.8
for p in sorted(pixels,key=lambda p:(p[1],p[0])):
    if all(math.dist(p,q)>=spacing for q in points): points.append(p)
assert 200<=len(points)<=512,len(points)
xy=[((x-127.5)/127.5,(127.5-y)/127.5) for x,y in points]
lines=[', '.join(f'{a:.6f}f, {b:.6f}f' for a,b in xy[i:i+6]) for i in range(0,len(xy),6)]
java='''package dev.winefox.skyfarer.weapon;

/** Generated by tools/export-fox3-emblem.py from black ink, not a rendered PNG. */
public final class Fox3EmblemData {
    public static final String SOURCE_SHA256 = "%s";
    private static final float[] POINTS = {
        %s
    };
    public static final int COUNT = POINTS.length / 2;
    public static float x(int point) { return POINTS[point * 2]; }
    public static float y(int point) { return POINTS[point * 2 + 1]; }
    private Fox3EmblemData() {}
}
'''%(hashlib.sha256(source.read_bytes()).hexdigest(),',\n        '.join(lines))
(root/'src/main/java/dev/winefox/skyfarer/weapon/Fox3EmblemData.java').write_text(java,encoding='utf-8')
preview=Image.new('RGB',(768,768),(12,15,24)); draw=ImageDraw.Draw(preview)
for x,y in points:
    px=x*3; py=y*3
    draw.ellipse((px-3,py-3,px+3,py+3),fill=(255,188,65))
dest=root/'build/reports/fox3-emblem-points.png'; dest.parent.mkdir(parents=True,exist_ok=True); preview.save(dest)
print(f'{len(points)} samples from {len(ink)} ink pixels / {len(pixels)} skeleton pixels; preview: {dest}')
